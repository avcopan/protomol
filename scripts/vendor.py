"""Copy extern/stereomolgraph/src/stereomolgraph into src/protomol/_vendor/.

The copy has its imports rewritten from `stereomolgraph` to
`protomol._vendor.stereomolgraph`, so it can't collide with the PyPI package.

Run with `pixi run vendor`; `pixi run vendor-check` fails if the copy is out of date.
"""

import argparse
import configparser
import re
import shutil
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
EXTERN = ROOT / "extern/stereomolgraph"
SOURCE = EXTERN / "src/stereomolgraph"
LICENSE = EXTERN / "LICENSE"
GITREPO = EXTERN / ".gitrepo"
VENDOR = ROOT / "src/protomol/_vendor"
TARGET = VENDOR / "stereomolgraph"
NEW = "protomol._vendor.stereomolgraph"

IMPORT = re.compile(r"^(\s*)(from|import) stereomolgraph\b", re.MULTILINE)
BARE_IMPORT = re.compile(r"^\s*import stereomolgraph\b(?!.*\bas\b).*$", re.MULTILINE)
STRING = re.compile(r"""["']stereomolgraph\b""")


class VendorError(Exception):
    """The upstream source can't be vendored safely."""


def rewrite(text: str, path: Path) -> str:
    """Rewrite `from stereomolgraph…` and `import stereomolgraph… as x` to `NEW`.

    Args:
        text: The source of an upstream module.
        path: Its path, for error messages.

    Returns:
        The source with its imports rewritten.

    Raises:
        VendorError: For `import stereomolgraph.x` without `as`, which would bind
            the name `protomol` once rewritten.
    """
    if bare := BARE_IMPORT.findall(text):
        msg = f"{path}: bare import without `as`: {bare}"
        raise VendorError(msg)
    for lineno, line in enumerate(text.splitlines(), start=1):
        if STRING.search(line):
            print(f"note: {path}:{lineno}: string names stereomolgraph: {line.strip()}")
    return IMPORT.sub(rf"\1\2 {NEW}", text)


def expected() -> dict[Path, str]:
    """Build the vendored files in memory.

    Returns:
        The content of each file under `VENDOR`, by path.
    """
    files: dict[Path, str] = {}
    for src in sorted(SOURCE.rglob("*")):
        if "__pycache__" in src.parts or not src.is_file():
            continue
        rel = src.relative_to(SOURCE)
        if src.suffix == ".py":
            files[TARGET / rel] = rewrite(read(src), src.relative_to(ROOT))
        elif src.name == "py.typed":
            files[TARGET / rel] = read(src)
    files[TARGET / "LICENSE"] = read(LICENSE)

    gitrepo = configparser.ConfigParser()
    gitrepo.read(GITREPO)
    sub = gitrepo["subrepo"]
    files[VENDOR / "__init__.py"] = (
        '"""Vendored third-party packages.\n'
        "\n"
        "GENERATED by `pixi run vendor`: never edit.\n"
        "\n"
        f"stereomolgraph: {sub['remote']}, branch {sub['branch']}, "
        f"commit {sub['commit']}\n"
        '(from extern/stereomolgraph, a git-subrepo; see scripts/vendor.py).\n"""\n'
    )
    return files


def existing() -> set[Path]:
    """List the files now under `VENDOR`.

    Returns:
        Their paths, without caches.
    """
    if not VENDOR.exists():
        return set()
    return {
        p for p in VENDOR.rglob("*") if p.is_file() and "__pycache__" not in p.parts
    }


def read(path: Path) -> str:
    """Read a file, keeping its line endings.

    Returns:
        Its text.
    """
    with path.open(encoding="utf-8", newline="") as f:
        return f.read()


def vendor(*, check: bool) -> int:
    """Write, or with `check` compare, the vendored files.

    Args:
        check: Only compare the files and report the ones that differ.

    Returns:
        The number of files that differ (missing, stale or changed).
    """
    files = expected()
    stale = existing() - files.keys()
    changed = [p for p, text in files.items() if not p.exists() or read(p) != text]
    if check:
        for path in sorted(stale | set(changed)):
            print(f"out of date: {path.relative_to(ROOT)}")
        return len(stale) + len(changed)

    shutil.rmtree(VENDOR, ignore_errors=True)
    for path, text in files.items():
        path.parent.mkdir(parents=True, exist_ok=True)
        with path.open("w", encoding="utf-8", newline="") as f:
            f.write(text)
    print(f"wrote {len(files)} files to {VENDOR.relative_to(ROOT)}")
    return 0


def main() -> int:
    """Run from the command line.

    Returns:
        The exit status.
    """
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--check", action="store_true", help="fail if the copy is out of date"
    )
    args = parser.parse_args()
    try:
        ndiff = vendor(check=args.check)
    except VendorError as err:
        print(f"error: {err}", file=sys.stderr)
        return 2
    if ndiff:
        print(f"{ndiff} files out of date: run `pixi run vendor`", file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
